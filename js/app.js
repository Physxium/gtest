function renderCurrentScreen() {

    renderHeader();


    if (
        state.screen === "home"
    ) {

        renderHome();

        return;

    }


    if (
        state.screen ===
        "reaction-ready"
    ) {

        showReactionReady();

        return;

    }


    if (
        state.screen ===
        "reaction-result"
    ) {

        showReactionResult();

        return;

    }


    if (
        state.screen ===
        "judgment-ready"
    ) {

        showJudgmentReady();

        return;

    }


    if (
        state.screen ===
        "judgment-result"
    ) {

        showJudgmentResult();

        return;

    }


    if (
        state.screen ===
        "multitask-ready"
    ) {

        showMultitaskReady();

        return;

    }


    if (
        state.screen ===
        "multitask-result"
    ) {

        showMultitaskResult();

        return;

    }


    if (
        state.screen ===
        "precision-ready"
    ) {

        showPrecisionReady();

        return;

    }


    if (
        state.screen ===
        "precision-result"
    ) {

        showPrecisionResult();

        return;

    }


    if (
        state.screen ===
        "prediction-ready"
    ) {

        showPredictionReady();

        return;

    }


    if (
        state.screen ===
        "prediction-result"
    ) {

        showPredictionResult();

    }

}


