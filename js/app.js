/* ------------------------------
   Home
------------------------------ */

function renderHome() {

    state.screen =
        "home";


    state.currentGame =
        0;


    gameProgressEl.textContent =
        t("ready");


    gameNameEl.textContent =
        t("testName");


    gameStatusEl.textContent =
        "";


    gameStageEl.innerHTML = `
        <div class="start-panel">

            <div class="game-instruction-box">
                ${t("startInstruction")}
            </div>


            <div class="start-mark">
                GT
            </div>


            <h2>
                ${t("startTitle")}
            </h2>


            <p>
                ${t("startDescription")}
            </p>


            <button
                id="startButton"
                class="primary-button"
                type="button"
            >
                ${t("startButton")}
            </button>


            ${renderDevMenu()}

        </div>
    `;


    document
        .getElementById(
            "startButton"
        )
        .addEventListener(
            "click",
            () => {

                playSound(
                    "click"
                );


                showReactionReady();

            }
        );


    if (!DEV_MODE) {
        return;
    }


    document
        .querySelectorAll(
            "[data-dev-game]"
        )
        .forEach(
            button => {

                button.addEventListener(
                    "click",
                    () => {

                        playSound(
                            "click"
                        );


                        const game =
                            button.dataset.devGame;


                        if (
                            game === "reaction"
                        ) {

                            showReactionReady();

                            return;

                        }


                        if (
                            game === "judgment"
                        ) {

                            showJudgmentReady();

                            return;

                        }


                        if (
                            game === "multitask"
                        ) {

                            showMultitaskReady();

                            return;

                        }


                        if (
                            game === "precision"
                        ) {

                            showPrecisionReady();

                            return;

                        }


                        if (
                            game === "prediction"
                        ) {

                            showPredictionReady();

                        }

                    }
                );

            }
        );

}


