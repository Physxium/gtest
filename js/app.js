function toggleLanguage() {

    if (
        state.screen.endsWith(
            "-playing"
        )
    ) {
        return;
    }


    state.language =
        state.language === "ko"
            ? "en"
            : "ko";


    document.documentElement.lang =
        state.language;


    renderCurrentScreen();

}


