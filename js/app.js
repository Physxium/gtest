const SCORE_ALPHABET =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";


function encodeScores(
    scoreValues
) {

    /*
        점수 5개 × 7bit = 35bit

        각 점수는 0~100 정수이므로
        7bit에 안전하게 들어간다.
    */

    let packed = 0;


    scoreValues.forEach(
        score => {

            packed =
                packed
                *
                128
                +
                score;

        }
    );


    /*
        35bit를 6개의 Base64 문자로 표현.
        6문자 = 36bit.

        항상 6자리 고정.
    */

    let encoded = "";


    for (
        let i = 0;
        i < 6;
        i++
    ) {

        const divisor =
            Math.pow(
                64,
                5 - i
            );


        const index =
            Math.floor(
                packed
                /
                divisor
            )
            %
            64;


        encoded +=
            SCORE_ALPHABET[
            index
            ];

    }


    return encoded;

}

function openFinalResult() {

    const scoreValues = [

        state.scores.reaction,
        state.scores.judgment,
        state.scores.multitask,
        state.scores.precision,
        state.scores.prediction

    ].map(
        score => {

            /*
                DEV에서 건너뛴 게임은
                결과 화면 테스트를 위해 0점 처리.
            */

            if (
                score === null
                ||
                score === undefined
            ) {

                return 0;

            }


            return Math.max(
                0,
                Math.min(
                    100,
                    Math.round(
                        score
                    )
                )
            );

        }
    );


    const encoded =
        encodeScores(
            scoreValues
        );


    window.location.href =
        `./result.html?r=${encoded}`;

}


